#!/usr/bin/env node
/* Regenerates ios/ui/RCGlyphData.inc from the approved prototype glyphs
   (design/uxui/js/icons.js) so native glyphs keep the exact same geometry.
   Usage: node ios/ui/tools/gen-glyphs.cjs > ios/ui/RCGlyphData.inc */
'use strict';
var fs = require('fs'), path = require('path');
var src = path.resolve(__dirname, '../../../design/uxui/js/icons.js');
global.window = global; global.K = {};
require('vm').runInThisContext(fs.readFileSync(src, 'utf8'), { filename: src });
var names = [], re = /^\s{4}(\w+): '/mg, m, text = fs.readFileSync(src, 'utf8');
while ((m = re.exec(text))) names.push(m[1]);
function attr(el, n) { var r = new RegExp('\\s' + n + '="([^"]*)"').exec(el); return r ? r[1] : null; }
var out = ['/* Generated by ios/ui/tools/gen-glyphs.cjs from design/uxui/js/icons.js. Do not edit. */'];
names.forEach(function (name) {
  var svg = K.glyph(name, 24, 'C'), els = svg.match(/<(path|rect|circle)\s[^>]*\/>/g) || [];
  els.forEach(function (el) {
    var shape = /^<(\w+)/.exec(el)[1].charAt(0);
    var fill = attr(el, 'fill'), stroke = attr(el, 'stroke');
    var paint = (stroke && fill === 'none') ? 's' : 'f';
    var color = paint === 's' ? stroke : fill;
    var flags = '';
    if (color && color !== 'C') flags += 'W';               /* fixed white detail: knocked out of the glyph */
    if (attr(el, 'stroke-dasharray')) flags += 'D';
    if (attr(el, 'opacity')) flags += 'H';
    var width = paint === 's' ? parseFloat(attr(el, 'stroke-width') || '2.2') : 0;
    var data;
    if (shape === 'p') data = attr(el, 'd');
    else if (shape === 'r') data = [attr(el, 'x'), attr(el, 'y'), attr(el, 'width'), attr(el, 'height'), attr(el, 'rx') || '0'].join(' ');
    else data = [attr(el, 'cx'), attr(el, 'cy'), attr(el, 'r')].join(' ');
    out.push('{"' + name + '", \'' + shape + '\', \'' + paint + '\', ' + width.toFixed(2) + 'f, "' + flags + '", "' + data + '"},');
  });
});
process.stdout.write(out.join('\n') + '\n');
